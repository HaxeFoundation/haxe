(* Generates the Config module of the vendored OCaml backend from the
   configuration of the compiler that builds it ([ocamlopt -config]), so that
   the generated code matches the runtime it is linked with.

   Usage: gen_config <ocamlopt> <config.generated.ml.in> <config.common.ml.in> *)

let read_file f = In_channel.with_open_bin f In_channel.input_all

let () =
  let ocamlopt = Sys.argv.(1) in
  let ic = Unix.open_process_args_in ocamlopt [| ocamlopt; "-config" |] in
  let config = Hashtbl.create 64 in
  (try
     while true do
       let line = input_line ic in
       match String.index_opt line ':' with
       | Some i ->
         let v = String.sub line (i + 1) (String.length line - i - 1) in
         let v = if String.length v > 0 && v.[0] = ' ' then String.sub v 1 (String.length v - 1) else v in
         Hashtbl.replace config (String.sub line 0 i) v
       | None -> ()
     done
   with End_of_file -> ());
  ignore (Unix.close_process_in ic);
  let get k = try Hashtbl.find config k with Not_found -> failwith ("ocamlopt -config: no " ^ k) in
  let opt k d = try Hashtbl.find config k with Not_found -> d in
  let strip_dot s = if String.length s > 0 && s.[0] = '.' then String.sub s 1 (String.length s - 1) else s in
  let subst = function
    | "QS" -> ""
    | "configure_input" -> "Generated by libs/jit/ocaml/gen from ocamlopt -config"
    | "ocaml_bindir" -> ""
    | "ocaml_libdir" -> get "standard_library_default"
    | "ccomptype" -> get "ccomp_type"
    | "CC" -> get "c_compiler"
    | "outputobj" -> "-o "
    | "cc_has_debug_prefix_map" | "as_has_debug_prefix_map" -> "false"
    | "bytecode_cflags" -> get "bytecode_cflags"
    | "bytecode_cppflags" -> get "bytecode_cppflags"
    | "native_cflags" -> get "native_cflags"
    | "native_cppflags" -> get "native_cppflags"
    | "zstd_libs" -> ""
    | "cclibs" -> get "native_c_libraries"
    | "native_ldflags" -> opt "native_ldflags" ""
    | "PACKLD" -> get "native_pack_linker"
    | "rpath" | "mksharedlibrpath" | "mkdll_exp" | "mkexe_exp" | "mkmaindll_exp" -> ""
    | "AR" -> "ar"
    | "supports_shared_libraries" -> get "supports_shared_libraries"
    | "natdynlink" -> get "native_dynlink"
    | "flambda" -> get "flambda"
    | "flambda_invariants" | "cmm_invariants" -> "false"
    | "windows_unicode" -> if get "windows_unicode" = "true" then "1" else "0"
    | "flat_float_array" -> get "flat_float_array"
    | "function_sections" -> get "function_sections"
    | "afl" -> get "afl_instrument"
    | "native_compiler" -> get "native_compiler"
    | "arch" -> get "architecture"
    | "model" -> get "model"
    | "system" -> get "system"
    | "AS" -> get "asm"
    | "asm_cfi_supported" -> get "asm_cfi_supported"
    | "frame_pointers" -> get "with_frame_pointers"
    | "reserved_header_bits" -> opt "reserved_header_bits" "0"
    | "exeext" -> get "ext_exe"
    | "OBJEXT" -> strip_dot (get "ext_obj")
    | "S" -> strip_dot (get "ext_asm")
    | "libext" -> strip_dot (get "ext_lib")
    | "SO" -> strip_dot (get "ext_dll")
    | "host" -> get "host"
    | "target" -> get "target"
    | "systhread_support" -> get "systhread_supported"
    | "flexdll_dir" -> ""
    | "ar_supports_response_files" -> "true"
    | "tsan" -> get "tsan"
    | k when String.ends_with ~suffix:"_MAGIC_NUMBER" k ->
      get (String.lowercase_ascii k)
    | k -> failwith ("unknown configuration variable @" ^ k ^ "@")
  in
  let expand s =
    let b = Buffer.create (String.length s) in
    let n = String.length s in
    let i = ref 0 in
    while !i < n do
      (match String.index_from_opt s (!i + 1) '@' with
       | Some j when s.[!i] = '@' && j - !i > 1
                     && String.for_all (fun c -> c = '_' || (c >= 'a' && c <= 'z')
                                                 || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9'))
                          (String.sub s (!i + 1) (j - !i - 1)) ->
         Buffer.add_string b (subst (String.sub s (!i + 1) (j - !i - 1)));
         i := j + 1
       | _ -> Buffer.add_char b s.[!i]; incr i)
    done;
    Buffer.contents b
  in
  if get "version" <> String.trim (List.hd (String.split_on_char '\n' (read_file Sys.argv.(4)))) then
    failwith ("the vendored OCaml backend is for OCaml "
              ^ String.trim (read_file Sys.argv.(4)) ^ ", not " ^ get "version");
  print_string (expand (read_file Sys.argv.(2)));
  print_string (expand (read_file Sys.argv.(3)))
