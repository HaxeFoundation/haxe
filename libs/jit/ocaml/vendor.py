#!/usr/bin/env python3
"""Vendors the native backend of the OCaml compiler into this directory.

Haxe cannot link compiler-libs: several of its modules have the same names as
modules of the Haxe compiler (Path, Lexer, Parser, Typecore...). The backend
is copied here instead, as the wrapped library [ocaml_backend], from an OCaml
source tree of exactly the version that builds Haxe (the generated code must
match the runtime it runs in).

Only the modules needed to go from Cmm to assembly are copied: the closure of
the modules used by the JIT, computed with ocamldep, without the middle end
(Cmmgen) and the translation from the typed tree (Translmod), whose entry
points are removed from Asmgen.

Usage: vendor.py <OCaml source tree> [--arch amd64]

Requires ocamldep, ocamllex and ocaml (the installed OCaml) for emit.mlp."""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

DIRS = ["utils", "parsing", "typing", "lambda", "file_formats", "middle_end",
        "middle_end/flambda", "middle_end/flambda/base_types",
        "asmcomp"]

ROOTS = ["Asmgen", "Emit", "Cmm_helpers", "Compilenv", "X86_proc", "X86_gas",
         "X86_dsl", "X86_ast", "Proc", "Arch", "Backend_var", "Debuginfo"]

CUTS = {"Translmod", "Cmmgen"}


def module_name(f):
    base = os.path.basename(f).split(".")[0]
    return base[0].upper() + base[1:]


def sources(src, arch):
    files = {}
    for d in DIRS + ["asmcomp/" + arch]:
        for f in sorted(os.listdir(os.path.join(src, d))):
            if re.match(r"\w+\.(ml|mli|mlp|mll)$", f):
                files.setdefault(module_name(f), []).append(os.path.join(d, f))
    files["Parser"] = ["boot/menhir/parser.ml", "boot/menhir/parser.mli"]
    files["MenhirLib"] = ["boot/menhir/menhirLib.ml", "boot/menhir/menhirLib.mli"]
    files["Config"] = ["utils/config.mli"]
    files["Domainstate"] = []   # generated, see DUNE
    # architecture-specific files override the generic ones of asmcomp
    for m, fs in files.items():
        specific = [f for f in fs if f.startswith("asmcomp/" + arch + "/")]
        if specific:
            exts = {os.path.splitext(f)[1] for f in specific}
            files[m] = specific + [f for f in fs if f not in specific
                                   and os.path.splitext(f)[1] not in exts]
    return files


def convert_mlp(src, f, dst):
    """emit.mlp to emit.ml, with the preprocessor of the OCaml sources"""
    cvt = tempfile.mktemp(suffix=".ml")
    subprocess.run(["ocamllex", "-q", "-o", cvt,
                    os.path.join(src, "tools/cvt_emit.mll")], check=True)
    with open(os.path.join(src, f)) as i, open(dst, "w") as o:
        subprocess.run(["ocaml", cvt], stdin=i, stdout=o, check=True)


def deps_of(src, f):
    path = os.path.join(src, f)
    args = ["ocamldep", "-modules"]
    if f.endswith(".mlp"):
        path = tempfile.mktemp(suffix=".ml")
        convert_mlp(src, f, path)
    elif f.endswith(".mll"):
        tmp = tempfile.mktemp(suffix=".ml")
        subprocess.run(["ocamllex", "-q", "-o", tmp, path], check=True)
        path = tmp
    out = subprocess.run(args + [path], capture_output=True, text=True, check=True).stdout
    return set(out.split(":", 1)[1].split()) if ":" in out else set()


def closure(src, files):
    deps = {}
    for m, fs in files.items():
        ds = set()
        for f in fs:
            ds |= deps_of(src, f)
        deps[m] = {d for d in ds if d in files and d != m and d not in CUTS}
    seen = set()
    stack = list(ROOTS)
    while stack:
        m = stack.pop()
        if m not in seen:
            seen.add(m)
            stack.extend(deps[m])
    return seen


def patch_asmgen(ml, mli):
    """Removes the compilation of implementations, which needs the middle end
    and the translation from the typed tree."""
    start = ml.index("let end_gen_implementation")
    end = ml.index("let asm_filename")
    ml = ml[:start] + ml[end:]
    start = ml.index("let compile_implementation ?toplevel")
    end = ml.index("let linear_gen_implementation")
    ml = ml[:start] + ml[end:]
    start = ml.index("(* For the native toplevel: generates generic functions")
    end = ml.index("let compile_unit ")
    ml = ml[:start] + ml[end:]
    start = mli.index("(** The type of converters from Lambda to Clambda. *)")
    end = mli.index("val compile_implementation_linear")
    mli = mli[:start] + mli[end:]
    return ml, mli


DUNE = """; Generated by ../vendor.py: the native backend of the OCaml compiler (see
; ../VERSION). Wrapped: several of its modules have the same names as modules
; of the Haxe compiler.

(library
	(name ocaml_backend)
	; the backend must be the one of the compiler that builds Haxe
	(enabled_if (= %%{ocaml_version} %(version)s))
	(flags (:standard -w -a -warn-error -a -strict-sequence -principal -safe-string -strict-formats))
	(modules_without_implementation %(intf_only)s)
	; Compression (compressed marshaling) needs the C library installed with
	; OCaml, as compiler-libs does
	(c_library_flags (-lcomprmarsh))
)

(rule
	(targets lexer.ml)
	(deps lexer.mll)
	(enabled_if (= %%{ocaml_version} %(version)s))
	(action (run %%{bin:ocamllex} -q -o %%{targets} %%{deps})))

; The layout of the domain state, from the header of the installed runtime
(rule
	(targets domainstate.ml)
	(deps domainstate.ml.c %%{ocaml_where}/caml/domain_state.tbl)
	(enabled_if (= %%{ocaml_version} %(version)s))
	(action (with-stdout-to domainstate.ml
		(run %%{cc} -E -P -I %%{ocaml_where}/caml domainstate.ml.c))))

(rule
	(targets domainstate.mli)
	(deps domainstate.mli.c %%{ocaml_where}/caml/domain_state.tbl)
	(enabled_if (= %%{ocaml_version} %(version)s))
	(action (with-stdout-to domainstate.mli
		(run %%{cc} -E -P -I %%{ocaml_where}/caml domainstate.mli.c))))

(rule
	(targets config.ml)
	(deps config.generated.ml.in config.common.ml.in ../VERSION)
	(enabled_if (= %%{ocaml_version} %(version)s))
	(action (with-stdout-to config.ml
		(run ../gen/gen_config.exe %%{ocamlopt} config.generated.ml.in config.common.ml.in ../VERSION))))
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("--arch", default="amd64")
    args = ap.parse_args()
    src = os.path.abspath(args.src)
    version = open(os.path.join(src, "VERSION")).readline().strip()
    files = sources(src, args.arch)
    mods = closure(src, files)
    out = os.path.join(HERE, "src")
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    copied = []
    for m in sorted(mods):
        for f in files[m]:
            base = os.path.basename(f)
            dst = os.path.join(out, base)
            if f.endswith(".mlp"):
                convert_mlp(src, f, dst[:-1])
                copied.append(f)
                continue
            shutil.copy(os.path.join(src, f), dst)
            copied.append(f)
    for name in ["config.generated.ml.in", "config.common.ml.in",
                 "domainstate.ml.c", "domainstate.mli.c"]:
        shutil.copy(os.path.join(src, "utils", name), os.path.join(out, name))
    ml = open(os.path.join(out, "asmgen.ml")).read()
    mli = open(os.path.join(out, "asmgen.mli")).read()
    ml, mli = patch_asmgen(ml, mli)
    open(os.path.join(out, "asmgen.ml"), "w").write(ml)
    open(os.path.join(out, "asmgen.mli"), "w").write(mli)
    shutil.copy(os.path.join(src, "LICENSE"), os.path.join(out, "LICENSE"))
    names = os.listdir(out)
    intf_only = sorted(n[:-4] for n in names if n.endswith(".mli")
                       and n[:-1] not in names and n[:-4] + ".mll" not in names
                       and n[:-4] != "config")
    with open(os.path.join(out, "dune"), "w") as f:
        f.write(DUNE % {"intf_only": " ".join(intf_only), "version": version})
    with open(os.path.join(HERE, "VERSION"), "w") as f:
        f.write(version + "\n" + args.arch + "\n")
    lines = sum(sum(1 for _ in open(os.path.join(src, f), errors="ignore"))
                for f in copied if not f.endswith(".mli"))
    print("OCaml %s (%s): %d modules, %d files, %d lines" % (
        version, args.arch, len(mods), len(copied), lines))


if __name__ == "__main__":
    main()
